function globalToSurahAyah(g) {
  let lo = 1, hi = 114;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (SURAH_OFFSETS[mid] <= g) lo = mid;
    else hi = mid - 1;
  }
  return { surah: lo, ayah: g - SURAH_OFFSETS[lo] + 1 };
}

function hizbRange(hizb) {
  return HIZB_RANGES[hizb];
}

